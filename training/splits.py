"""Frozen data splits.  Never train on the validation or held-out maps.

Generated maps are deterministic in (seed, tier, flags).  Seeds 0–9,999 are the
training pool; 10,000–10,999 are validation; 20,000+ are OOD configurations
(larger maps, deeper key chains — generated by the evaluator, not the collector).

Freedoom maps 1–22 train, 23–32 are held out for the whole project.
"""

from __future__ import annotations

import json
from pathlib import Path

FREEDOOM_TRAIN = [f"MAP{i:02d}" for i in range(1, 23)]
FREEDOOM_EVAL = [f"MAP{i:02d}" for i in range(23, 33)]

GEN_TRAIN = (0, 9_999)
GEN_VAL = (10_000, 10_999)
GEN_OOD = (20_000, 29_999)

SPLIT_PATH = Path(__file__).with_name("splits.json")


def write_split_file() -> None:
    SPLIT_PATH.write_text(json.dumps({
        "freedoom_train": FREEDOOM_TRAIN,
        "freedoom_eval": FREEDOOM_EVAL,
        "generated_train": list(GEN_TRAIN),
        "generated_val": list(GEN_VAL),
        "generated_ood": list(GEN_OOD),
    }, indent=1))


def freedoom_train() -> list[str]:
    return list(FREEDOOM_TRAIN)


def freedoom_eval() -> list[str]:
    return list(FREEDOOM_EVAL)


if __name__ == "__main__":
    write_split_file()
    print(SPLIT_PATH.read_text())
